// Loudness is a shipping invariant, not a matter of taste.
//
// The bug this was written for: the Wunderwaffe DG-2. shot_dg2.mp3 was 1.79 s
// of flat electrical fizz whose loudest 10 ms sat 140 ms after the trigger
// pull, with 5.8 % of its energy below 200 Hz. It never cracked, because
// nothing ever checked that a gunshot's transient is at the front of the file.
// Forty-two of the sixty-four shot_*.mp3 files had the same defect, several
// with up to 60 ms of leading silence before the shot.
//
// The wider defect was level. The library spanned 32 dB of max-momentary
// loudness — snarl1 was 12 dB hotter than any rifle and clipped at +3.9 dBTP,
// while step2 sat at -34.7 — so js/audio.js was full of per-call constants
// (groan *= 0.32) that existed only to undo an asset's accidental level. Fifty
// files exceeded the -1 dBTP ceiling.
//
// This checks four things, all of which the mix-1 mastering pass established:
//
//   1. nothing exceeds the true-peak ceiling
//   2. every gunshot's loudest 10 ms lands in the first 80 ms
//   3. the weapon family stays inside a deliberate loudness ladder, and every
//      other family stays inside its own allowance
//   4. the families stay in the intended order, loudest to quietest
//
// scripts/audio-loudness.json is generated by the mastering pass from the files
// that are actually on disk. Its `bytes` field is checked against every file so
// the manifest cannot silently go stale: re-encode an asset without re-running
// the pass and this fails. When ffmpeg is available the peak numbers are also
// re-derived from the audio itself rather than trusted.
import assert from 'node:assert';
import { readFile, stat, readdir } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const run = promisify(execFile);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const audioDir = join(root, 'assets', 'audio');

const manifest = JSON.parse(await readFile(join(root, 'scripts', 'audio-loudness.json'), 'utf8'));
const files = manifest.files;
const CEILING = manifest.ceilingDbtp;
assert.equal(CEILING, -1.0, 'the true-peak ceiling is -1.0 dBTP');

// ---------------------------------------------------------------------------
// 0. the manifest describes exactly what ships, and is not stale
// ---------------------------------------------------------------------------
const onDisk = (await readdir(audioDir)).filter((f) => f.endsWith('.mp3')).map((f) => f.slice(0, -4)).sort();
const listed = Object.keys(files).sort();
assert.deepEqual(listed, onDisk,
  'scripts/audio-loudness.json must cover exactly the mp3s in assets/audio (regenerate it after adding or removing a sound)');

for (const [name, m] of Object.entries(files)) {
  const info = await stat(join(audioDir, `${name}.mp3`));
  assert.equal(info.size, m.bytes,
    `${name}.mp3 changed on disk but scripts/audio-loudness.json was not regenerated — its measurements no longer describe the shipped file`);
}

// ---------------------------------------------------------------------------
// 1. nothing clips
// ---------------------------------------------------------------------------
const over = Object.entries(files).filter(([, m]) => m.dbtp > CEILING + 0.001);
assert.equal(over.length, 0,
  `every asset must sit at or under ${CEILING} dBTP; over: ${over.map(([n, m]) => `${n}=${m.dbtp}`).join(', ')}`);

// ---------------------------------------------------------------------------
// 2. a gunshot's transient is at the front of the file
// ---------------------------------------------------------------------------
const TRANSIENT_WINDOW = 0.08;
const late = Object.entries(files)
  .filter(([n, m]) => n.startsWith('shot_') && m.peakAt > TRANSIENT_WINDOW);
assert.equal(late.length, 0,
  `a gunshot's loudest 10 ms must land within the first ${TRANSIENT_WINDOW * 1000} ms — a shot that peaks later has no crack. `
  + `Late: ${late.map(([n, m]) => `${n}@${m.peakAt}s`).join(', ')}`);

// ---------------------------------------------------------------------------
// 3. per-family loudness spread
// ---------------------------------------------------------------------------
// Allowance per family, in dB, on the 200 ms max-momentary window. `weapon` is
// wider than the rest on purpose: a rocket launcher is meant to be louder than
// an MP40, and manifest.weaponClassOffset is that ladder. `music` is measured
// on integrated loudness rather than a window, so its momentary figures vary
// with how dense the arrangement is. `foley` is wide only because of
// knuckles.mp3, which is 132 ms long — shorter than the measurement window, so
// it cannot be driven to the family target without clipping; the other 42 foley
// files sit inside 1.8 dB of each other.
const SPREAD = {
  weapon: 5.0, blast: 1.0, impact: 2.5, casing: 1.5, foley: 9.0, step: 1.0,
  zvoice: 1.0, pvoice: 1.0, announce: 1.0, ui: 1.0, tick: 0.5, stinger: 1.0,
  music: 6.0, amb: 1.0, ambloop: 0.5, song: 0.5,
};
const byFamily = new Map();
for (const [name, m] of Object.entries(files)) {
  if (!byFamily.has(m.family)) byFamily.set(m.family, []);
  byFamily.get(m.family).push({ name, ...m });
}
assert.deepEqual([...byFamily.keys()].sort(), Object.keys(SPREAD).sort(),
  'every family in the manifest needs a declared spread allowance');

for (const [fam, rows] of byFamily) {
  const ls = rows.map((r) => r.lufs200);
  const spread = Math.max(...ls) - Math.min(...ls);
  const worst = rows.slice().sort((a, b) => a.lufs200 - b.lufs200);
  assert.ok(spread <= SPREAD[fam] + 0.001,
    `family "${fam}" spans ${spread.toFixed(2)} dB (allowed ${SPREAD[fam]}); `
    + `quietest ${worst[0].name}=${worst[0].lufs200}, loudest ${worst[worst.length - 1].name}=${worst[worst.length - 1].lufs200}`);
}

// Every weapon must land on its own rung of the ladder, not merely inside the
// family band — otherwise a shotgun could drift down to SMG level and still pass.
const base = manifest.weaponBaseTarget;
for (const r of byFamily.get('weapon')) {
  const want = base + manifest.weaponClassOffset[r.cls] + (r.pap ? manifest.papOffset : 0);
  assert.ok(r.lufs200 <= want + 0.35,
    `${r.name} is ${(r.lufs200 - want).toFixed(2)} dB over its class target (${want.toFixed(2)})`);
  // Short bursts cannot always be driven all the way up to target without
  // crushing them, so the downward tolerance is looser than the upward one.
  assert.ok(r.lufs200 >= want - 2.5,
    `${r.name} is ${(want - r.lufs200).toFixed(2)} dB under its class target (${want.toFixed(2)})`);
}

// ---------------------------------------------------------------------------
// 4. the families stay in the intended order
// ---------------------------------------------------------------------------
const median = (fam) => {
  const v = byFamily.get(fam).map((r) => r.lufs200).sort((a, b) => a - b);
  return v[Math.floor(v.length / 2)];
};
// Blasts on top; the announcer sits fractionally above the guns because a
// max-ammo call has to survive a firefight; then the horde, UI, bullet impacts,
// footsteps and finally shell casings.
const ORDER = ['blast', 'announce', 'weapon', 'zvoice', 'ui', 'impact', 'step', 'tick', 'casing'];
for (let i = 1; i < ORDER.length; i++) {
  assert.ok(median(ORDER[i - 1]) > median(ORDER[i]),
    `the mix ladder is inverted: "${ORDER[i - 1]}" (${median(ORDER[i - 1])}) must sit above "${ORDER[i]}" (${median(ORDER[i])})`);
}
assert.ok(median('pvoice') === median('zvoice'),
  'character lines and zombie voices share one voice-family target');

// ---------------------------------------------------------------------------
// 4b. every weapon declares what it ejects, and every casing take exists
// ---------------------------------------------------------------------------
// The bug this was written for: js/audio.js decided whether to play a shell
// casing with `!CONCUSSIVE.has(shot)` — the set of shots that rattle the
// player's ears — so the Ray Gun and the Thundergun clattered brass onto the
// concrete after every shot while the PTRS-41 silently swallowed a 14.5 mm
// case. Ejection is now an explicit per-weapon field, and this is what stops it
// drifting the next time a weapon is added: a definition with no `casing` falls
// back to silence at runtime and fails here.
const weaponsSrc = await readFile(join(root, 'js', 'weapons.js'), 'utf8');
const casingsSrc = await readFile(join(root, 'js', 'audio', 'casings.js'), 'utf8');

const declaredKinds = new Set(
  [...casingsSrc.matchAll(/^\s{2}(\w+): Object\.freeze\(\{ sample: '([\w_]+)'/gm)].map((m) => m[1]),
);
assert.ok(declaredKinds.size >= 4, 'js/audio/casings.js declares no casing kinds');

const weaponBlock = weaponsSrc.slice(
  weaponsSrc.indexOf('export const WEAPONS = {'),
  weaponsSrc.indexOf('\n};\n', weaponsSrc.indexOf('export const WEAPONS = {')),
);
const defs = [...weaponBlock.matchAll(/\n {2}(\w+): \{\n {4}name: '[^']*', cls: '(\w+)',([^\n]*)/g)];
assert.ok(defs.length >= 30, `only found ${defs.length} weapon definitions to check`);
const missing = [];
const badKind = [];
for (const [, id, , rest] of defs) {
  const m = /\bcasing: '(\w+)'/.exec(rest);
  if (!m) missing.push(id);
  else if (m[1] !== 'none' && !declaredKinds.has(m[1])) badKind.push(`${id}=${m[1]}`);
}
assert.equal(missing.length, 0,
  `every weapon must declare what it ejects (casing: none|${[...declaredKinds].join('|')}); missing: ${missing.join(', ')}`);
assert.equal(badKind.length, 0,
  `unknown casing kind: ${badKind.join(', ')} — js/audio/casings.js has no shaping for it`);

// Energy and wonder weapons have no cartridge at all. Assert it directly rather
// than trusting that whoever adds the next one remembers.
for (const [, id, cls, rest] of defs) {
  if (cls !== 'wonder' && cls !== 'melee' && cls !== 'tactical') continue;
  assert.match(rest, /\bcasing: 'none'/,
    `${id} is a ${cls} weapon and must not eject a casing`);
}

// Three variants per kind per surface, or the engine's variant picker silently
// falls through to the synth bank for the missing ones.
for (const kind of declaredKinds) {
  for (const surface of ['concrete', 'metal']) {
    for (let v = 1; v <= 3; v++) {
      const stem = `casing_${kind}_${surface}${v}`;
      assert.ok(files[stem], `missing casing take ${stem}.mp3`);
    }
  }
}

// ---------------------------------------------------------------------------
// 5. re-derive the peaks from the audio when ffmpeg is present
// ---------------------------------------------------------------------------
let haveFfmpeg = true;
try {
  await run('ffmpeg', ['-version']);
} catch {
  haveFfmpeg = false;
}

if (haveFfmpeg) {
  // Every gunshot plus a deterministic slice of everything else: enough to
  // catch a hand-edited manifest without turning this into a minute-long job.
  const sample = listed.filter((n, i) => n.startsWith('shot_') || i % 7 === 0);
  let checked = 0;
  for (const name of sample) {
    const { stderr } = await run('ffmpeg', [
      '-hide_banner', '-nostats', '-i', join(audioDir, `${name}.mp3`),
      '-filter_complex', 'ebur128=peak=true', '-f', 'null', '-',
    ], { maxBuffer: 1 << 22 });
    const peaks = [...stderr.matchAll(/Peak:\s*(-?\d+(?:\.\d+)?)\s*dBFS/g)].map((m) => Number(m[1]));
    assert.ok(peaks.length, `ffmpeg reported no peak for ${name}`);
    const measured = Math.max(...peaks);
    // ffmpeg prints one decimal, so allow a rounding step over the ceiling.
    assert.ok(measured <= CEILING + 0.1,
      `${name}.mp3 measures ${measured} dBTP, over the ${CEILING} dBTP ceiling`);
    assert.ok(Math.abs(measured - files[name].dbtp) <= 1.0,
      `${name}.mp3 measures ${measured} dBTP but the manifest claims ${files[name].dbtp} — the manifest does not describe this file`);
    checked++;
  }
  console.log(`Audio loudness validation passed: ${listed.length} assets under ${CEILING} dBTP, `
    + `${byFamily.get('weapon').length} gunshots front-loaded and inside the class ladder, `
    + `${byFamily.size} families within their spread allowances, ${checked} re-measured with ffmpeg.`);
} else {
  console.log(`Audio loudness validation passed: ${listed.length} assets under ${CEILING} dBTP, `
    + `${byFamily.get('weapon').length} gunshots front-loaded and inside the class ladder, `
    + `${byFamily.size} families within their spread allowances (ffmpeg absent — manifest checks only).`);
}
