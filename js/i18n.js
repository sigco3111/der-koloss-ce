// ----- Runtime state -----
let _lang = 'en';
const _dicts = { en: EN, ko: KO };

function _dict() {
  return _dicts[_lang] || EN;
}

export function getLanguage() {
  return _lang;
}

export function setLanguage(lang) {
  if (lang !== 'ko' && lang !== 'en') lang = 'en';
  _lang = lang;
  return _lang;
}

export function t(key) {
  const d = _dict();
  if (d && Object.prototype.hasOwnProperty.call(d, key)) return d[key];
  // Fallback to EN, then to the key itself (prefixed so missing strings
  // are visible at runtime instead of silently rendering empty).
  if (EN && Object.prototype.hasOwnProperty.call(EN, key)) return EN[key];
  return `~${key}`;
}

// Replace {placeholder} tokens from a values object. Pure-string utility;
// callers usually do `t(key).replaceAll(...)` directly, but this helper
// is exported for sites that want cleaner template semantics.
export function format(template, values) {
  if (!template || !values) return template || '';
  return String(template).replace(/\{(\w+)\}/g, (_, k) => (k in values ? String(values[k]) : `{${k}}`));
}

// Init: install the Korean dictionary globally so other modules can read
// from `(globalThis.__koDict)` if they want to skip the resolver. This is
// belt-and-suspenders for the no-bundler case — every site just imports `t`.
export function initKorean() {
  if (typeof globalThis !== 'undefined') {
    globalThis.__koDict = KO;
    globalThis.__enDict = EN;
    globalThis.__currentLang = 'ko';
  }
}

// Auto-install Korean at module load (no-bundler + module imports → safe
// because any consumer that imports { t } will get the same shared dict).
initKorean();
